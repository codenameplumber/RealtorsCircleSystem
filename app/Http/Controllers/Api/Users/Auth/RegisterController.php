<?php

namespace App\Http\Controllers\Api\Users\Auth;

use App\Http\Controllers\Controller;
use App\Models\UsersTable;
use App\Support\EmailThrottle;
use Illuminate\Http\Request;
use Illuminate\Support\Carbon;
use Illuminate\Support\Facades\Hash;
use Illuminate\Support\Facades\Log;
use Illuminate\Support\Facades\Validator;
use Illuminate\Support\Str;
use App\Mail\Users\EmailVerificationMail;
use App\Mail\Users\PasswordResetMail;
use Illuminate\Support\Facades\Mail;
use Illuminate\Support\Facades\Auth;
use Illuminate\Support\Facades\DB; // For database interaction with password_reset_tokens

class RegisterController extends Controller
{

    #========First Step of Registration==========#
    public function step1(Request $request)
    {
        $validator = Validator::make($request->all(), [
            'First_name' => ['required', 'string', 'max:255'],
            'Last_name' => ['required', 'string', 'max:255'],
            'Email' => ['required', 'string', 'email', 'max:255', 'unique:users_tables'],
            'Phone' => ['required', 'string', 'unique:users_tables'],
            'Password' => ['required', 'string', 'min:8', 'confirmed'],
        ]);

        if ($validator->fails()) {
            return response()->json(['errors' => $validator->errors()], 422);
        }

        try {
            $user = UsersTable::create([
                'First_name' => $request->First_name,
                'Last_name' => $request->Last_name,
                'Email' => $request->Email,
                'Phone' => $request->Phone,
                'password' => Hash::make($request->Password),
                'steps_signup' => 'step1_initiated',
                'Bio' => null,
                'Address' => null,
                'Specialization' => null,
                'Yrs_experience' => null,
                'Notification' => json_encode(['email' => true]),
                '2fa' => 'disabled',
                'Status' => 'pending',
                'State' => null,
                'Local_area' => null,
                'Country' => null,
            ]);

            // api_token is guarded against mass assignment — set it explicitly.
            $user->forceFill(['api_token' => hash('sha256', Str::random(60))])->save();

            $this->sendVerificationLink(
                $user,
                'Action Required: Verify Your Email to Start Your Journey!',
                "Welcome to " . config('app.name') . ", " . $user->First_name . "! We're thrilled to have you. To activate your account and move forward, please click the button below to verify your email address. This is a crucial first step!"
            );

            return response()->json([
                'message' => 'Registration step 1 successful. Please verify your email to continue.',
                'user_id' => $user->id,
                'next_step' => 'email_verification',
                'status' => 'pending_email_verification'
            ], 201);

        } catch (\Exception $e) {
            Log::error("Registration Step 1 Error: " . $e->getMessage());
            return response()->json(['message' =>'An error occurred during registration. Please try again.'], 500);
        }
    }

    /**
     * Issue a fresh single-use verification token and mail the link.
     *
     * The token is generated by the model, which stores only its hash; the
     * plaintext exists just long enough to be embedded in this URL. Suppressed
     * silently when the recipient has exhausted their mail budget — see
     * EmailThrottle.
     */
    private function sendVerificationLink(UsersTable $user, string $subject, string $body): void
    {
        if (! EmailThrottle::allows($user->Email, 'verification')) {
            return;
        }

        $token = $user->generateEmailVerificationToken();

        $verificationUrl = route('users.auth.verification.verify', [
            'token' => $token,
            'email' => $user->Email,
        ]);

        try {
            Mail::to($user->Email)->send(new EmailVerificationMail($user, $verificationUrl, $subject, $body));
        } catch (\Throwable $e) {
            Log::error("Verification mail failed for user #{$user->id}: " . $e->getMessage());
        }
    }

    #=========Handling Email Verification===============#
    public function verifyEmail(Request $request, $token)
    {
        $user = UsersTable::where('Email', $request->query('email'))->first();

        // The token is the credential here. It was previously accepted without
        // being checked at all, which let anyone verify any address just by
        // naming it in the query string.
        if (! $user || $user->email_verified_at || ! $user->isValidEmailVerificationToken($token)) {
            return response()->json([
                'message' => 'Email verification failed or Link invalid',
                'url' => '/login'
            ], 400);
        }

        $user->markEmailVerified();
        $user->steps_signup = 'step1_completed';
        $user->save();

        // **EMAIL AFTER EMAIL VERIFICATION IS COMPLETE**
        try {
            Mail::to($user->Email)->send(new EmailVerificationMail(
                $user,
                null, // No verification URL needed now
                'Email Verified: You are Ready for Step 2!', // Clear subject for completion
                "Fantastic, " . $user->First_name . "! Your email address has been successfully verified. This is a crucial milestone! You can now securely log in and proceed to Step 2 to provide your basic Address Information." // Encouraging message
            ));
        } catch (\Throwable $e) {
            Log::error("Post-verification mail failed for user #{$user->id}: " . $e->getMessage());
        }

        return response()->json([
                'message' => 'Email verification successful,next login',
                'url' => '/login'
            ], 200);

    }

    #========User Login and Token Generation==========#
    public function login(Request $request)
    {
        $validator = Validator::make($request->all(), [
            'email' => ['required', 'email'],
            'password' => ['required'],
        ]);

        if ($validator->fails()) {
            return response()->json(['errors' => $validator->errors()], 422);
        }

        if (Auth::attempt(['Email' => $request->email, 'password' => $request->password])) {
            $user = Auth::user();

            // Mirror the web login gates — an unverified or unapproved account
            // must not receive a working API token.
            if (! $user->email_verified_at) {
                return response()->json(['message' => 'Please verify your email address before signing in.'], 403);
            }

            if ($user->Status !== 'active') {
                return response()->json([
                    'message' => $user->Status === 'pending'
                        ? 'Your account is pending admin approval.'
                        : 'Your account is not active. Please contact support.',
                ], 403);
            }

            $token = Str::random(60);
            $user->forceFill(['api_token' => hash('sha256', $token)])->save();

            return response()->json([
                'message' => 'Login successful',
                'token' => $token,
                'user' => $user,
                'current_step' => $user->steps_signup,
            ], 200);
        } else {
            return response()->json(['message' => 'Invalid credentials'], 401);
        }
    }


     #========Request Password Reset Link==========#
    public function forgotPassword(Request $request)
    {
        $validator = Validator::make($request->all(), [
            'email' => ['required', 'email'],
        ]);

        if ($validator->fails()) {
            return response()->json(['errors' => $validator->errors()], 422);
        }

        // Identical response on every path below — the existence of the
        // account, mail failures and throttling must all be indistinguishable
        // to the caller, or this endpoint becomes an enumeration oracle.
        $genericResponse = response()->json([
            'message' => 'If your email address exists in our database, you will receive a password reset link shortly.',
        ], 200);

        $user = UsersTable::where('Email', $request->email)->first();

        if (! $user || ! EmailThrottle::allows($request->email, 'password-reset')) {
            return $genericResponse;
        }

        // Generate a new token and store it in the password_reset_tokens table
        $token = Str::random(60);
        DB::table('password_reset_tokens')->updateOrInsert(
            ['email' => $user->Email],
            ['token' => Hash::make($token), 'created_at' => now()] // Hash the token before storing
        );

        $resetUrl = url(config('app.url') . '/rc/v1/auth/reset-password?token=' . $token . '&email=' . urlencode($user->Email));

        try {
            Mail::to($user->Email)->send(new PasswordResetMail(
                $user,
                $resetUrl,
                'Action Required: Reset Your Password', // Subject
                "You are receiving this email because we received a password reset request for your account. Click the button below to reset your password. This link is valid for " . config('auth.passwords.users.expire') . " minutes." // Body message
            ));
        } catch (\Exception $e) {
            // Log it, but never surface the exception text: the driver message
            // carries SMTP hostnames, credentials and local filesystem paths.
            Log::error("Password reset mail failed for user #{$user->id}: " . $e->getMessage());
        }

        return $genericResponse;
    }

    #========Reset Password==========#
    public function resetPassword(Request $request)
    {
        $validator = Validator::make($request->all(), [
            'email' => ['required', 'email'],
            'token' => ['required', 'string'],
            'password' => ['required', 'string', 'min:8', 'confirmed'],
        ]);

        if ($validator->fails()) {
            return response()->json(['errors' => $validator->errors()], 422);
        }

        // Retrieve the token from the password_reset_tokens table
        $passwordReset = DB::table('password_reset_tokens')
                            ->where('email', $request->email)
                            ->first();

        if (! $passwordReset
            || ! Hash::check($request->token, $passwordReset->token)
            || $this->resetTokenHasExpired($passwordReset->created_at)) {
            return response()->json(['message' => 'Invalid or expired password reset token.'], 400);
        }

        // Find the user
        $user = UsersTable::where('Email', $request->email)->first(); // Use 'Email'

        if (!$user) {
            return response()->json(['message' => 'User not found.'], 404);
        }

        // Update the password and rotate the API token, invalidating any
        // session an attacker may already hold.
        $token = Str::random(60);

        $user->forceFill([
            'Password'  => Hash::make($request->password),
            'api_token' => hash('sha256', $token),
        ])->save();

        // Delete the password reset token from the table
        DB::table('password_reset_tokens')->where('email', $request->email)->delete();

        EmailThrottle::clear($request->email, 'password-reset');

        // **EMAIL AFTER PASSWORD RESET IS COMPLETE**
        try {
            Mail::to($user->Email)->send(new EmailVerificationMail( // Reusing EmailVerificationMail for simplicity or create new mailer
                $user,
                null, // No verification URL needed
                'Your Password Has Been Reset Successfully!', // Clear subject
                "Hello " . $user->First_name . "! Your password for your " . config('app.name') . " account has been successfully reset. If you did not initiate this change, please contact our support team immediately." // Informative message
            ));
        } catch (\Throwable $e) {
            Log::error("Password reset confirmation mail failed for user #{$user->id}: " . $e->getMessage());
        }

        return response()->json([
            'message' => 'Password reset successfully.',
            'token' => $token, // Return the new API token if logged in
            'user' => $user,
        ], 200);
    }

    /**
     * Carbon 3 returns a *signed* difference, so the previous
     * `now()->diffInMinutes($createdAt) > $expire` comparison yielded a
     * negative number for every past timestamp and was never true — reset
     * tokens never expired. Compare against an absolute deadline instead,
     * which has no sign to get wrong.
     */
    private function resetTokenHasExpired(?string $createdAt): bool
    {
        if (! $createdAt) {
            return true;
        }

        $expireMinutes = (int) config('auth.passwords.users.expire', 60);

        return Carbon::parse($createdAt)->addMinutes($expireMinutes)->isPast();
    }
}
